#!/usr/bin/env python3
"""Writes headless/translation_id.h: a hash of the sources that decide how a guest shader is
translated. The kept translations (EDEN_UP_SHADER_PREP) are stamped with it instead of with the
installed eboot's size and write time, so installing a build that translates the same keeps them:
the first boot after every install took 158 to 305 s to translate everything again, a repeat boot
36 to 38 s (12 Nov 2026).

usage: gen-translation-id.py SOURCE_ROOT OUTPUT_HEADER
"""
import hashlib
import pathlib
import sys

# Relative to SOURCE_ROOT/src. Directories are walked; every file in them counts.
TRANSLATION_SOURCES = (
    "shader_recompiler",
    "video_core/shader_environment.cpp",
    "video_core/shader_environment.h",
    "video_core/renderer_vulkan/vk_pipeline_prep.cpp",
    "video_core/renderer_vulkan/vk_pipeline_prep.h",
)


def translation_id(source_root: pathlib.Path) -> str:
    src = source_root / "src"
    files = []
    for entry in TRANSLATION_SOURCES:
        path = src / entry
        if path.is_dir():
            files += [p for p in path.rglob("*") if p.is_file()]
        elif path.is_file():
            files.append(path)
        else:
            raise SystemExit(f"gen-translation-id: {path} is missing")
    digest = hashlib.sha256()
    for path in sorted(files, key=lambda p: p.relative_to(src).as_posix()):
        name = path.relative_to(src).as_posix().encode()
        data = path.read_bytes()
        digest.update(len(name).to_bytes(4, "little") + name)
        digest.update(len(data).to_bytes(8, "little") + data)
    return digest.hexdigest()[:16]


def main() -> None:
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    ident = translation_id(pathlib.Path(sys.argv[1]))
    out = pathlib.Path(sys.argv[2])
    text = ("// Generated by tools/gen-translation-id.py: do not edit.\n#pragma once\n"
            f'#define EDEN_TRANSLATION_ID "{ident}"\n')
    # Left alone when unchanged, so the build does not recompile for nothing.
    if not out.exists() or out.read_text() != text:
        out.write_text(text)
    print(f"Translation id {ident}")


if __name__ == "__main__":
    main()
